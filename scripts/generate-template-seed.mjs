#!/usr/bin/env node
/**
 * Builds supabase/migrations/0005_launch_templates.sql from the template
 * sources in supabase/templates/ (catalog.json + <slug>.html + <slug>.css).
 *
 *   node scripts/generate-template-seed.mjs          write the migration
 *   node scripts/generate-template-seed.mjs --check  fail if it is out of date
 *
 * The database stays the source of truth at runtime; this only produces the
 * one-off seed. It has no dependencies. The checks below mirror
 * lib/templates/sanitize.ts and lib/templates/render.ts so a seeded template
 * can still be opened and re-saved in /admin/templates without being altered.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const srcDir = path.join(root, "supabase/templates");
const outFile = path.join(root, "supabase/migrations/0005_launch_templates.sql");

// Tag allow-list is read from the app's sanitizer so the two cannot drift.
const sanitizeSource = fs.readFileSync(path.join(root, "lib/templates/sanitize.ts"), "utf8");
const tagsBlock = /const TAGS = \[([\s\S]*?)\];/.exec(sanitizeSource);
if (!tagsBlock) throw new Error("Could not read the TAGS allow-list from lib/templates/sanitize.ts");
const ALLOWED_TAGS = new Set([...tagsBlock[1].matchAll(/"([a-z0-9]+)"/g)].map((m) => m[1]));
const ALLOWED_ATTRS = new Set(["class", "id", "style", "title", "lang", "href", "target", "rel", "src", "alt", "width", "height", "colspan", "rowspan"]);

function problemsIn(slug, html, css) {
  const out = [];
  for (const m of html.matchAll(/<\/?([a-zA-Z][a-zA-Z0-9]*)([^>]*)>/g)) {
    const tag = m[1].toLowerCase();
    if (!ALLOWED_TAGS.has(tag)) out.push(`<${tag}> is not allowed by the sanitizer`);
    for (const a of m[2].matchAll(/\s([a-zA-Z-]+)=/g)) {
      if (!ALLOWED_ATTRS.has(a[1].toLowerCase())) out.push(`attribute "${a[1]}" is not allowed by the sanitizer`);
    }
  }
  if (/\{\{\{/.test(html) || /\{\{\s*&/.test(html)) out.push("unescaped Mustache tags are not allowed");
  if (/\{\{\s*[=>]/.test(html)) out.push("Mustache delimiters/partials are not allowed");
  if (/<!--/.test(html)) out.push("HTML comments are stripped by the sanitizer");
  const stack = [];
  for (const m of html.matchAll(/\{\{\s*([#^/])\s*([\w.]+)\s*\}\}/g)) {
    if (m[1] === "/") {
      if (stack.pop() !== m[2]) out.push(`unbalanced Mustache section near {{/${m[2]}}}`);
    } else stack.push(m[2]);
  }
  if (stack.length) out.push(`unclosed Mustache section {{#${stack.at(-1)}}}`);
  if (/@import/i.test(css)) out.push("CSS @import is not allowed");
  if (/expression\s*\(|behavior\s*:|-moz-binding|javascript:/i.test(css)) out.push("CSS contains a disallowed construct");
  if (/<\/?style/i.test(css)) out.push("CSS must not contain <style> tags");
  if (/url\(\s*(?!["']?\s*data:)/i.test(css) || /url\(\s*(?!["']?\s*data:)/i.test(html)) out.push("url() may only point at data: URIs");
  if (html.includes("$tpl$") || css.includes("$tpl$")) out.push("contains the SQL quoting tag $tpl$");
  return out.map((p) => `${slug}: ${p}`);
}

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const catalog = JSON.parse(fs.readFileSync(path.join(srcDir, "catalog.json"), "utf8"));
const errors = [];
const rows = catalog.map((t) => {
  const html = fs.readFileSync(path.join(srcDir, `${t.slug}.html`), "utf8").trim();
  const css = fs.readFileSync(path.join(srcDir, `${t.slug}.css`), "utf8").trim();
  errors.push(...problemsIn(t.slug, html, css));
  return `  (${q(t.id)}, ${q(t.slug)}, ${q(t.name)}, ${q(t.description)}, ${q(t.category)}, ${t.sort_order}, true,\n   $tpl$${html}$tpl$,\n   $tpl$${css}$tpl$)`;
});
if (errors.length) {
  console.error(errors.join("\n"));
  process.exit(1);
}

const sql = `-- 0005: the ten launch resume templates.
-- GENERATED by scripts/generate-template-seed.mjs from supabase/templates/.
-- Edit the sources there and regenerate; do not edit this file by hand.
--
-- Safe to re-run: ids and slugs are fixed, and "on conflict do nothing" means
-- nothing is duplicated and any template an admin has since edited (or a
-- template that already uses one of these slugs) is left untouched.
-- Run it in the Supabase SQL editor or with the CLI (as the postgres owner).
-- Runs after 0004, which creates public.templates.

insert into public.templates
  (id, slug, name, description, category, sort_order, is_published, html, css)
values
${rows.join(",\n")}
on conflict do nothing;
`;

if (process.argv.includes("--check")) {
  const current = fs.existsSync(outFile) ? fs.readFileSync(outFile, "utf8") : "";
  if (current !== sql) {
    console.error("0005_launch_templates.sql is out of date. Run: npm run templates:generate");
    process.exit(1);
  }
  console.log(`OK: ${catalog.length} templates, migration is up to date.`);
} else {
  fs.writeFileSync(outFile, sql);
  console.log(`Wrote ${path.relative(root, outFile)} (${catalog.length} templates).`);
}
